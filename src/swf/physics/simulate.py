"""`python -m swf simulate-energy`: NASA weather -> constrained simulated T1 (solar) / T5 (wind) kW."""

import pandas as pd

from swf.core.paths import CONFIG_DIR, DOCS_DIR, INTERIM_DIR
from swf.core.settings import load_settings
from swf.coverage.report import _table, write_auto_block
from swf.physics.common import clearsky, is_night
from swf.physics.constraints import enforce
from swf.physics.solar import ac_cap_kw, pdc0_w, simulate_solar
from swf.physics.wind import load_power_curve, simulate_wind

OPENER = "Generated by `python -m swf simulate-energy`. Do not edit inside this block."


def simulate(weather: pd.DataFrame, s, curve=None) -> pd.DataFrame:
    """PRD 6 constraint layer on every simulated target."""
    return enforce(
        pd.DataFrame(
            {
                "t1_kw": simulate_solar(weather, s),
                "t5_kw": simulate_wind(weather, s, curve),
            }
        ),
        s,
    )


def render_physics(energy: pd.DataFrame, s) -> str:
    cap, pdc0 = ac_cap_kw(s), pdc0_w(s) / 1000
    curve_name = (
        "manufacturer Theoretical_Power_Curve re-binned (PRD §4.3)"
        if (CONFIG_DIR / s.wind.power_curve_csv).exists()
        else "parametric fallback"
    )
    L = [
        OPENER, "",
        f"- pdc0 (inverter DC input): {pdc0:.1f} kW (dc_kwp {s.solar.dc_kwp:g} / dc_ac_ratio {s.solar.dc_ac_ratio:g}).",
        f"- AC cap: {cap:.1f} kW (eta_inv_nom {s.solar.eta_inv_nom:g} x pdc0).",
        f"- Loss {s.solar.loss_pct:g}% from config, applied on the DC side.",
        f"- Solar nRMSE is normalised by the AC cap ({cap:.1f} kW, D-06); wind nRMSE by rated {s.wind.rated_kw:g} kW (D-07).",
        (f"- Wind power curve: {curve_name}; accepted parametric fallback rated*(v^3-vin^3)/(vr^3-vin^3) "
        "(the PRD simple cubic gives 382 kW at 8 m/s against about 1,527 kW on the real curve)."),
        "", "### Clear-sky 21 March, hourly t1_kw (UTC label)", "",
    ]  # fmt: skip
    idx = pd.date_range("2024-03-21 00:00", periods=24, freq="h", tz="UTC", name="time")
    cs = clearsky(idx, s)[["ghi", "dni", "dhi"]].assign(temp=25.0, ws10=4.0)
    cs = enforce(pd.DataFrame({"t1_kw": simulate_solar(cs, s)}), s)
    L += _table(
        ["hour UTC", "t1_kw"],
        [[f"{t:%H:00}", f"{v:.1f}"] for t, v in cs["t1_kw"].items()],
    )
    yr = energy.index.year
    night = is_night(energy.index, s)
    rows = [
        [y, f"{g['t1_kw'].max():.1f}", int((g["t1_kw"] >= cap - 1e-9).sum()), f"{g['t1_kw'].sum() / s.solar.dc_kwp:.0f}",
         f"{g['t1_kw'].mean() / s.solar.dc_kwp * 100:.1f}", f"{g['t5_kw'].mean() / s.wind.rated_kw * 100:.1f}"]
        for y, g in energy.groupby(yr)
    ]  # fmt: skip
    L += ["### Simulated energy per year (NASA weather)", ""]
    L += _table(
        [
            "year",
            "max t1 kW",
            "hours at cap",
            "yield kWh/kWp",
            "solar CF % (vs dc_kwp)",
            "wind CF % (vs rated)",
        ],
        rows,
    )
    mw = energy["t5_kw"].groupby(energy.index.month).mean() / s.wind.rated_kw * 100
    L += ["### Monthly wind CF %", ""] + _table(
        ["month", "CF %"], [[m, f"{v:.1f}"] for m, v in mw.items()]
    )
    L.append(
        f"Night hours with t1_kw > 0: {int(((energy['t1_kw'] > 0) & night).sum())} (must be 0)."
    )
    return "\n".join(L)


def run(args) -> int:
    s = load_settings()
    src = INTERIM_DIR / "weather_nasa.parquet"
    if not src.exists():
        print("run `python -m swf build-weather` first")
        return 1
    energy = simulate(pd.read_parquet(src), s, load_power_curve(s))
    energy.to_parquet(INTERIM_DIR / "energy_sim.parquet")
    block = render_physics(energy, s)
    write_auto_block(DOCS_DIR / "data_notes.md", block, name="physics")
    print(block)
    return 0
