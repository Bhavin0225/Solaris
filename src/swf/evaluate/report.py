log = logging.getLogger("swf.evaluate")
OPENER = "Generated by `python -m swf evaluate`. Do not edit inside this block."
_CSV = {"index": False, "float_format": "%.6g", "lineterminator": "\n"}
_HORIZONS = ["1", "6", "24", "48", "72", "all"]
_SEASONS = ["all", "monsoon", "dry"]
_VARS = ("rh", "ws10", "ws_hub", "ghi")
_LEADS = (
    ("d1", "weather_gfs_pr_d1"),
    ("d2", "weather_gfs_pr_d2"),
    ("d3", "weather_gfs_pr_d3"),
    ("stitched", "weather_gfs_hf"),
)
_B3 = ("baseline3_corrected", "baseline3_raw")


def load_split(split, target, root) -> dict:
    d = Path(root) / split
    return {p.stem: read_long(split, p.stem, root, target=target) for p in sorted(d.glob("*.parquet"))}


def with_official(frames, choice, target) -> dict:
    df = frames[f"baseline3_{choice['choice'][target]}"].copy()
    df["model"] = pd.Categorical(["baseline3"] * len(df))
    return {**frames, "baseline3": df}


def score_split(split, s, cfg, root, choice):
    lbs, bds = [], []
    for t in TARGETS:
        frames = with_official(load_split(split, t, root), choice, t)
        wide, models = align_models(frames, t), sorted(frames)
        lbs.append(leaderboard_rows(wide, models, t, s, cfg))
        bds.append(breakdown(wide, models, t, s, cfg))
    out = []
    for df in (pd.concat(lbs), pd.concat(bds)):
        df.insert(0, "split", split)
        df["feature_spec_hash"] = spec_hash()
        out.append(df.reset_index(drop=True))
    return out[0], out[1]


def _sorted(df, splits):
    k = pd.DataFrame(
        {
            "a": df["split"].map({x: i for i, x in enumerate(splits)}),
            "b": df["target"].map({x: i for i, x in enumerate(TARGETS)}),
            "c": df["model"].astype(str),
        },
        index=df.index,
    )
    if "horizon" in df:
        k["d"] = df["horizon"].map({x: i for i, x in enumerate(_HORIZONS)})
        k["e"] = df["season"].map({x: i for i, x in enumerate(_SEASONS)})
    return df.loc[k.sort_values(list(k.columns), kind="stable").index].reset_index(drop=True)


def gfs_bias(interim_dir, s, cfg) -> pd.DataFrame:
    """D-04: remaining GFS-vs-NASA bias on validation only; committed coefficients, no refit."""
    d = Path(interim_dir)
    a, b = cfg.splits.val
    nasa = pd.read_parquet(d / "weather_nasa.parquet").loc[a:b]
    coefs = load_coefs()
    rows = []
    for lead, name in _LEADS:
        raw = pd.read_parquet(d / f"{name}.parquet").loc[a:b]
        cor = apply_correction(raw, coefs, s)
        cor["ghi"] = raw["ghi"]  # ghi is not corrected
        for variant, g in (("corrected", cor), ("raw", raw)):
            ref = nasa.reindex(g.index)
            day = daytime_mask(g.index, s, cfg.eval.daytime_zenith_deg)
            for v in _VARS:
                x, y = g[v].to_numpy("float64"), ref[v].to_numpy("float64")
                ok = np.isfinite(x) & np.isfinite(y) & (day if v == "ghi" else True)
                e = x[ok] - y[ok]
                rows.append(
                    {
                        "lead": lead, "variant": variant, "variable": v, "n": int(ok.sum()),
                        "gfs_mean": x[ok].mean() if ok.any() else np.nan,
                        "nasa_mean": y[ok].mean() if ok.any() else np.nan,
                        "bias": e.mean() if ok.any() else np.nan,
                        "rmse": float(np.sqrt((e**2).mean())) if ok.any() else np.nan,
                    }
                )  # fmt: skip
    out = pd.DataFrame(rows)
    out["feature_spec_hash"] = spec_hash()
    return out


def plots(lb, bd, bias, out_dir) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    out_dir = Path(out_dir)
    save = {"dpi": 120, "metadata": {"Software": None}}
    v = bd[(bd["split"] == "val") & (bd["season"] == "all") & (bd["horizon"] != "all")]
    models = sorted(v["model"].astype(str).unique())
    fig, axes = plt.subplots(1, len(TARGETS), figsize=(20, 4))
    for ax, t in zip(axes, TARGETS, strict=True):
        for m in models:
            g = v[(v["target"] == t) & (v["model"].astype(str) == m)]
            ax.plot(g["horizon"].astype(int), g["rmse"], marker="o", label=m)
        ax.set_title(t)
        ax.set_xlabel("horizon (h)")
        ax.set_ylabel("RMSE")
    axes[0].legend(fontsize=6)
    fig.tight_layout()
    fig.savefig(out_dir / "rmse_by_horizon_val.png", **save)
    plt.close(fig)

    lv = lb[lb["split"] == "val"]
    fig, ax = plt.subplots(figsize=(10, 4))
    w = 0.8 / len(models)
    for i, m in enumerate(models):
        g = lv[lv["model"].astype(str) == m].set_index("target").reindex(list(TARGETS))
        ax.bar(np.arange(len(TARGETS)) + i * w, g["skill_vs_baseline3"], w, label=m)
    ax.set_xticks(np.arange(len(TARGETS)) + 0.4 - w / 2, list(TARGETS))
    ax.set_ylabel("skill vs baseline3 (1 - RMSE/RMSE_ref)")
    ax.legend(fontsize=6)
    fig.tight_layout()
    fig.savefig(out_dir / "skill_val.png", **save)
    plt.close(fig)

    c = bias[bias["variant"] == "corrected"]
    fig, ax = plt.subplots(figsize=(8, 4))
    for i, (lead, _) in enumerate(_LEADS):
        g = c[c["lead"] == lead].set_index("variable").reindex(list(_VARS))
        ax.bar(np.arange(len(_VARS)) + i * 0.2, g["bias"], 0.2, label=lead)
    ax.set_xticks(np.arange(len(_VARS)) + 0.3, list(_VARS))
    ax.set_ylabel("corrected GFS - NASA (val 2024)")
    ax.legend()
    fig.tight_layout()
    fig.savefig(out_dir / "gfs_bias_val.png", **save)
    plt.close(fig)


def _f(x, d=3):
    return "n/a" if x is None or not np.isfinite(x) else f"{x:.{d}f}"


def render_evaluation(lb, choice, bias) -> str:
    L = [OPENER, "", "## Evaluation (leaderboard, breakdowns, GFS bias)", "", f"feature_spec_hash: {spec_hash()}", ""]
    L += [
        "Scoring conventions:",
        "",
        "- Splits purge origins whose 72 h targets cross a boundary, with no extra 168 h embargo (D-06): lag/rolling history features are inputs, not labels, and reading late-2023 weather to forecast early 2024 is exactly what the live site does.",
        "- GTI is not used as a covariate (D-05); GHI/DNI/DHI plus geometry cover it.",
        "- Persistence for t1_kw and ghi uses the same hour of the most recent observed day; both targets are scored daytime only (I1), midpoint zenith < 85 deg at target time.",
        "- No lead-age feature (I2): it is constant in stitched training covariates.",
        "- Stitched Historical Forecast training covariates are short-lead analyses, a documented train/serve skew (W1) quantified by the stitched-vs-lead-matched gap below.",
        "- Truth = NASA POWER weather + energy_sim kW; persistence is computed on the truth series (stronger than the live site could do).",
        "- nRMSE norm: t1_kw solar AC capacity, t5_kw rated kW, rh/ghi/ws10 mean of actuals on the shared sample.",
        "- Skill = 1 - RMSE/RMSE_ref on the shared index of all models; monsoon = UTC target months 6-9; horizons exact 1/6/24/48/72 plus all.",
        "- Previous Runs 10 m variables start 2024-01-19..21 and hub wind about 2024-02-16..18, so the val shared index starts there; previous_day{k} issue instant is approximate (RESEARCH A5).",
        "",
        f"D-03a: {choice['rule']}.",
        "",
    ]
    vr = choice["val_rmse"]
    L += _table(
        ["target", "choice", "val RMSE corrected", "val RMSE raw"],
        [[t, choice["choice"][t], _f(vr[t]["corrected"]), _f(vr[t]["raw"])] for t in TARGETS],
    )
    L += _table(
        ["split", "target", "model", "rmse", "nrmse_pct", "skill_vs_baseline3", "skill_vs_persistence", "n_shared"],
        [
            [r.split, r.target, r.model, _f(r.rmse), _f(r.nrmse_pct, 2), _f(r.skill_vs_baseline3), _f(r.skill_vs_persistence), r.n_shared]
            for r in lb.itertuples()
        ],
    )  # fmt: skip
    L += ["Stitched minus lead-matched corrected baseline-3 RMSE on val (covariate skew):", ""]
    v = lb[lb["split"] == "val"].set_index(["target", "model"])["rmse"]
    for t in TARGETS:
        L.append(f"- {t}: {_f(v[(t, 'baseline3_stitched_corrected')] - v[(t, 'baseline3_corrected')], 4)}")
    L += ["", "Remaining GFS-vs-NASA bias on val 2024: see reports/evaluation/gfs_bias_val.csv.", ""]
    return "\n".join(L)


def run(args, out_dir=None, notes_path=None, pred_root=None, choice_path=None, interim_dir=None) -> int:
    out_dir = Path(out_dir) if out_dir else REPORTS_DIR / "evaluation"
    notes_path = Path(notes_path) if notes_path else DOCS_DIR / "data_notes.md"
    root = Path(pred_root) if pred_root else PROCESSED_DIR / "predictions"
    choice_path = Path(choice_path) if choice_path else CONFIG_DIR / "baseline3_choice.json"
    interim = Path(interim_dir) if interim_dir else INTERIM_DIR
    s, cfg = load_settings(), load_features_cfg()
    splits = ["val", "test"] if args.split == "all" else [args.split]
    for sp in splits:
        if not any((root / sp).glob("*.parquet")):
            print("run `python -m swf baselines` first")
            return 1
    if "val" in splits:
        if any(not (interim / f"{n}.parquet").exists() for n in ["weather_nasa", *(n for _, n in _LEADS)]):
            print("run `python -m swf build-weather` first")
            return 1
        frames = {
            m: pd.concat([read_long("val", m, root, target=t) for t in TARGETS], ignore_index=True) for m in _B3
        }
        new = select_baseline3(frames, s, cfg)
        if not choice_path.exists():
            save_choice(new, choice_path)
        elif load_choice(choice_path)["choice"] != new["choice"]:
            log.warning("recomputed baseline-3 choice differs from frozen %s; keeping the frozen file", choice_path)
    try:
        choice = load_choice(choice_path)  # D-03a: no test scoring without the val-frozen choice
    except FileNotFoundError as e:
        print(e)
        return 1
    lbs, bds = [], []
    for sp in splits:  # val first, then test
        lb, bd = score_split(sp, s, cfg, root, choice)
        lbs.append(lb)
        bds.append(bd)
    lb, bd = (_sorted(pd.concat(x, ignore_index=True), splits) for x in (lbs, bds))
    out_dir.mkdir(parents=True, exist_ok=True)
    lb.to_csv(out_dir / "leaderboard.csv", **_CSV)
    bd.to_csv(out_dir / "breakdown.csv", **_CSV)
    if "val" in splits:
        bias = gfs_bias(interim, s, cfg)
        bias.to_csv(out_dir / "gfs_bias_val.csv", **_CSV)
        plots(lb, bd, bias, out_dir)
        write_auto_block(notes_path, render_evaluation(lb, choice, bias), name="evaluation")
    print(lb[["split", "target", "model", "rmse", "skill_vs_baseline3"]].to_string(index=False))
    return 0
