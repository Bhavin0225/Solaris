"""`python -m swf features`: document the feature spec hash and split ranges in data_notes (FEAT-01, FEAT-04)."""

import argparse
import logging
from pathlib import Path

from swf.core.paths import DOCS_DIR
from swf.core.settings import FeaturesCfg, load_features_cfg
from swf.coverage.report import _table, write_auto_block
from swf.features.spec import feature_spec, spec_hash
from swf.features.splits import render_splits

log = logging.getLogger("swf.features")

OPENER = "Generated by `python -m swf features`. Do not edit inside this block."


def render_features(cfg: FeaturesCfg, spec: dict) -> str:
    out = [OPENER, "", "## Features and splits", ""]
    out += [f"- Time convention: {spec['time_convention']}", f"- Lead mapping: {spec['lead_mapping']}"]
    out += [f"- Spec hash: `{spec_hash(spec)}` (spec_version {spec['spec_version']})", ""]
    out += _table(["feature set", "columns"], [[n, len(c)] for n, c in spec["sets"].items()])
    out += [f"- {n}" for n in spec["notes"]] + [""]
    out.append(render_splits(cfg))
    return "\n".join(out)


def run(args: argparse.Namespace, notes_path: Path | None = None) -> int:
    cfg = load_features_cfg()
    block = render_features(cfg, feature_spec(cfg))
    log.info("feature spec hash %s", spec_hash(feature_spec(cfg)))
    write_auto_block(notes_path or DOCS_DIR / "data_notes.md", block, name="features")
    print(block)
    return 0
