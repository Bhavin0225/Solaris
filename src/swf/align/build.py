"""`python -m swf build-weather`: raw cache -> verified, cleaned canonical tables + data_notes AUTO blocks."""

import logging

import numpy as np
import pandas as pd

from swf.align.adapters import OFFSETS, load_source
from swf.align.clean import REPORT_COLS, clean
from swf.align.consistency import (
    LOG_ONLY,
    VARS,
    apply_correction,
    decide,
    fit_correction,
    monthly_table,
    save_coefs,
)
from swf.align.timestamps import met_lag, verify
from swf.core.paths import CONFIG_DIR, DOCS_DIR, INTERIM_DIR
from swf.core.settings import Settings, load_settings
from swf.coverage.report import _table, write_auto_block
from swf.physics.common import solar_position

log = logging.getLogger("swf.align")

OPENER = "Generated by `python -m swf build-weather`. Do not edit inside this block."
LAGS = range(-2, 3)


def source_years(s: Settings) -> dict[str, tuple[int, int]]:
    om, n = s.data.openmeteo, s.data.nasa
    return {
        "nasa": (n.start_year, n.end_year),
        "era5": om.era5_years,
        "gfs_hf": om.historical_forecast_years,
        **{f"gfs_pr_d{d}": om.previous_runs_years for d in (1, 2, 3)},
    }  # gfs_live excluded: adapter-only here, served in Phase 5


def _f(v, d=2) -> str:
    return (
        "n/a" if v is None or (isinstance(v, float) and np.isnan(v)) else f"{v:.{d}f}"
    )


def render_timestamps(results: dict[str, dict], met: dict) -> str:
    L = [OPENER, "", "### Per-group offsets applied (D-10)", ""]
    L += _table(
        ["source family", "group", "shift h"],
        [[f, g, _f(o.total_seconds() / 3600, 1)] for (f, g), o in OFFSETS.items()],
    )
    L += ["### Summary per source (D-13 rule)", ""]
    rows = [
        [src, _f(r["onset_exact"] * 100, 1), _f(r["onset_tol"] * 100, 1), _f(r["onset_tol_opposite"] * 100, 1),
         _f(r["pooled"], 3), "PASS" if r["passed"] else "FAIL"]
        for src, r in results.items()
    ]  # fmt: skip
    L += _table(
        [
            "source",
            "onset exact %",
            "onset {0,+1} %",
            "opposite convention %",
            "pooled centroid h",
            "result",
        ],
        rows,
    )
    L += ["### Centroid difference per source x year (h)", ""]
    rows = []
    for src, r in results.items():
        for y, v in sorted(r["per_year"].items()):
            rows.append(
                [
                    src,
                    y,
                    _f(v, 3)
                    if y in r["full_years"]
                    else f"{_f(v, 3)} (partial (not gating))",
                ]
            )
    L += _table(["source", "year", "centroid h"], rows)
    L += [
        "### Met-group lag check, NASA vs shifted ERA5 on fit years (D-14, reported, not gating)",
        "",
    ]
    rows = [
        [c, *[_f(m["corr"][k], 4) for k in LAGS], m["best_lag_h"]]
        for c, m in met.items()
    ]
    L += _table(["variable", *[f"r @ {k:+d} h" for k in LAGS], "best lag h"], rows)
    return "\n".join(L)


def render_cleaning(report: pd.DataFrame) -> str:
    L = [
        OPENER,
        "",
        "Only rows with a non-zero value are listed; all other source x variable x year cells are 0.",
        "",
    ]
    num = [
        "pct_missing_before",
        "pct_missing_after",
        "clipped_low",
        "clipped_high",
        "night_zeroed",
    ]
    nz = report[(report[num] != 0).any(axis=1)]
    L += _table(
        list(REPORT_COLS),
        [[r.source, r.variable, r.year, _f(r.pct_missing_before, 3), _f(r.pct_missing_after, 3),
          r.clipped_low, r.clipped_high, r.night_zeroed] for r in nz.itertuples()],
    )  # fmt: skip
    for src in report["source"].unique():
        part = report[report["source"] == src]
        if (part[num] == 0).all(axis=1).any():
            L.append(
                f"- {src}: every other variable x year cell had 0.0% missing, 0 clipped and 0 night-zeroed."
            )
    return "\n".join(L) + "\n"


def _mt(t: pd.DataFrame) -> list[str]:
    rows = [
        [
            r.variable,
            "all" if r.month == 0 else r.month,
            r.n,
            _f(r.nasa_mean, 3),
            _f(r.bias, 3),
            _f(r.rmse, 3),
            _f(r.corr, 3),
        ]
        for r in t.itertuples()
    ]
    return _table(
        ["variable", "month", "n", "NASA mean", "bias (ref-NASA)", "RMSE", "corr"], rows
    )


def render_consistency(table, decisions, heldout_raw, heldout_corr) -> str:
    L = [OPENER, "", "### NASA vs ERA5, fit years (temp and pressure are log-only)", ""]
    L += _mt(table)
    L += ["### Correction decision (D-17)", ""]
    L += _table(
        ["variable", "rule", "months exceeding", "corrected"],
        [
            [
                v,
                d["threshold"],
                ",".join(map(str, d["months_exceeding"])) or "-",
                "yes" if d["correct"] else "no",
            ]
            for v, d in decisions.items()
        ],
    )
    L += [
        "### Held-out raw vs corrected (diagnostic only, never used for selection)",
        "",
    ]
    for name, t in (("raw", heldout_raw), ("corrected", heldout_corr)):
        t = t[(t["month"] == 0) & t["variable"].isin(VARS)]
        L += [f"Held-out {name} (all months):", ""]
        L += _mt(t)
    return "\n".join(L)


def run(args) -> int:
    s = load_settings()
    notes = DOCS_DIR / "data_notes.md"
    INTERIM_DIR.mkdir(parents=True, exist_ok=True)
    results, reports, clean_frames = {}, [], {}
    for src, (y0, y1) in source_years(s).items():
        frame = load_source(src, s)
        results[src] = verify(frame["ghi"], s)
        cleaned, rep = clean(
            frame, s, source=src,
            start=pd.Timestamp(f"{y0}-01-01 00:00", tz="UTC"), end=pd.Timestamp(f"{y1}-12-31 23:00", tz="UTC"),
        )  # fmt: skip
        cleaned.to_parquet(INTERIM_DIR / f"weather_{src}.parquet")
        clean_frames[src] = cleaned
        reports.append(rep)
    nasa, era5 = clean_frames["nasa"], clean_frames["era5"]

    mid = nasa.index + pd.Timedelta(minutes=30)
    cosz = np.cos(np.radians(solar_position(nasa.index, s)["zenith"].to_numpy()))
    day = (solar_position(nasa.index, s)["zenith"].to_numpy() < 80) & (
        nasa["ghi"].to_numpy() > 0
    )
    ratio = (
        (nasa["dni"].to_numpy() * cosz + nasa["dhi"].to_numpy())
        / nasa["ghi"].to_numpy()
    )[day]
    log.info(
        "NASA GHI closure median=%.3f p5-p95=%.3f..%.3f (n=%d, %s)",
        np.nanmedian(ratio),
        *np.nanpercentile(ratio, [5, 95]),
        len(ratio),
        mid[0],
    )

    met = met_lag(nasa, era5, s, years=s.align.fit_years)
    table = monthly_table(nasa, era5, s, years=s.align.fit_years)
    decisions = decide(table, s)
    coefs = fit_correction(nasa, era5, s, [v for v in VARS if decisions[v]["correct"]])
    save_coefs(coefs, CONFIG_DIR / "bias_correction.json")
    ho = (s.align.fit_years[1] + 1, s.data.openmeteo.era5_years[1])
    heldout_raw = monthly_table(nasa, era5, s, years=ho)
    heldout_corr = monthly_table(nasa, apply_correction(era5, coefs, s), s, years=ho)

    write_auto_block(notes, render_timestamps(results, met), name="timestamps")
    write_auto_block(
        notes, render_cleaning(pd.concat(reports, ignore_index=True)), name="cleaning"
    )
    write_auto_block(
        notes,
        render_consistency(table, decisions, heldout_raw, heldout_corr),
        name="consistency",
    )

    failed = [k for k, r in results.items() if not r["passed"]]
    print(
        f"sources: {len(results)} written; corrected: {[v for v in VARS if decisions[v]['correct']]}; log-only: {list(LOG_ONLY)}"
    )
    if failed:
        print(f"FAIL timestamp verification: {failed}")
        return 1
    return 0
