OPENER = "Generated by `python -m swf validate`. Do not edit inside this block."


def _f(v, d=1):
    return f"{v:.{d}f}"


def render_validation(m: dict) -> str:
    st = m["settings"]
    L = [OPENER, "", "### Solar (Kaggle Plant 1 gating, Plant 2 non-gating)", ""]
    head = ["plant", "gating", "rows", "ts dropped (partial inverters)", "dc_kwp anchor", "AC cap kW",
            "tuned loss %", "tune nRMSE %", "held-out nRMSE %", "full nRMSE %",
            "held-out @cfg loss %", "full @cfg loss %", "hourly nRMSE %", "MBE %", "Faiman full nRMSE %",
            "zero-AC daytime % worst/median", "pass"]  # fmt: skip
    rows = []
    for name, p in m["solar"].items():
        rows.append([
            name, "yes" if p["gating"] else "no", p["n_rows"], p["ts_partial_dropped"], _f(p["dc_kwp"]),
            _f(p["ac_cap_kw"]), f"{p['loss_pct_tuned']}" + (" (edge)" if p["loss_edge"] else ""),
            _f(p["tune_nrmse_pct"], 2), _f(p["heldout_nrmse_pct"], 2), _f(p["full_nrmse_pct"], 2),
            _f(p["heldout_nrmse_at_config_loss_pct"], 2), _f(p["full_nrmse_at_config_loss_pct"], 2),
            _f(p["hourly_nrmse_pct"], 2), _f(p["mbe_pct"], 2), _f(p["full_nrmse_faiman_pct"], 2),
            f"{p['zero_ac_daytime_pct_worst_inverter']:.1f} / {p['zero_ac_daytime_pct_median_inverter']:.1f}",
            "yes" if p["pass"] and p["pass_at_config_loss"] else "no",
        ])  # fmt: skip
    L += _table(head, rows)
    L += [
        f"nRMSE = RMSE / plant AC cap on daytime rows (IRRADIATION > {st['day_irradiation_kw_m2']:g} kW/m2); "
        f"gate = held-out from {st['heldout_start_local']} (local {st['local_timezone']}) at tuned and at "
        f"configured loss ({st['config_loss_pct']:g}%), target <= {st['solar_target_pct']:g}%.",
        "",
        "### Loss curve (tune period)", "",
    ]  # fmt: skip
    names = list(m["solar"])
    keys = list(m["solar"][names[0]]["loss_curve"])
    L += _table(
        ["loss %"] + [f"{n} nRMSE %" for n in names],
        [[k] + [_f(m["solar"][n]["loss_curve"][k], 2) for n in names] for k in keys],
    )
    w = m["wind"]
    L += ["### Wind (T1, 10-min rows, nRMSE / rated kW)", ""]
    L += _table(
        ["slice", "rows", "simulated nRMSE %", "manufacturer-curve nRMSE %", "pass"],
        [
            [k, v["n"], _f(v["sim_nrmse_pct"], 2), _f(v["reference_nrmse_pct"], 2),
             "yes" if v["sim_nrmse_pct"] <= min(w["target_pct"], v["reference_nrmse_pct"], w["prd_reference_nrmse_pct"]) else "no"]
            for k, v in w["slices"].items()
        ],
    )  # fmt: skip
    L += [
        f"PRD pre-project reference: {w['prd_reference_nrmse_pct']:.1f}%", "",
        f"availability config {w['availability_config_pct']:.1f}% vs measured {w['availability_measured_pct']:.1f}% "
        "(ws > threshold, LV <= 0)", "",
        f"energy ratio LV / curve: {w['energy_ratio']:.3f}",
    ]  # fmt: skip
    return "\n".join(L)


def _round(o, nd=3):
    if isinstance(o, float):
        return round(o, nd)
    if isinstance(o, dict):
        return {k: _round(v, nd) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_round(v, nd) for v in o]
    return o


def write_outputs(metrics: dict, series: dict, out_dir: Path, notes_path: Path, caps: dict) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    text = json.dumps(_round(metrics), indent=2, sort_keys=True) + "\n"
    with open(out_dir / "metrics.json", "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    for k, df in series.items():
        scatter(df["sim"], df["act"], out_dir / f"{k}_scatter.png", f"{k}: simulated vs actual", caps[k])
    write_auto_block(notes_path, render_validation(metrics), name="validation")


def _file(files: dict, name: str) -> Path:
    if name not in files:
        raise SystemExit(f"configured Kaggle file {name} is not among the expected files")
    return files[name]


def validate_all(s, vc, files: dict):
    vs, solar, series, caps = vc.solar, {}, {}, {}
    ref = None
    for name, pc in vs.plants.items():  # plant_1 (gating) first, its tuned loss is Plant 2's reference
        df, stats = ks.load_plant(_file(files, pc.generation_csv), _file(files, pc.weather_csv), pc, vs)
        solar[name] = ks.validate_plant(df, stats, s, vs, pc.gating, None if pc.gating else ref)
        if pc.gating and ref is None:
            ref = solar[name]["loss_pct_tuned"]
        sp = ks.plant_settings(s, stats["peak_ac_kw"], solar[name]["loss_pct_tuned"])
        day = ks.daytime(df, vs)
        series[f"solar_{name}"] = pd.DataFrame({"sim": ks.simulate_plant(df, sp)[day], "act": df["ac_kw"][day]})
        caps[f"solar_{name}"] = float(ac_cap_kw(sp))
    t1 = kw.load_t1(_file(files, vc.wind.t1_csv), vc.wind)
    sim = kw.simulate_t1(t1, s, vc.wind)
    series["wind"] = pd.DataFrame({"sim": sim, "act": t1["lv_kw"]})
    caps["wind"] = float(s.wind.rated_kw)
    metrics = {
        "solar": solar,
        "wind": kw.wind_metrics(t1, sim, s, vc.wind),
        "settings": {
            "day_irradiation_kw_m2": vs.day_irradiation_kw_m2,
            "loss_grid_pct": list(vs.loss_grid_pct),
            "heldout_start_local": vs.heldout_start_local.isoformat(),
            "solar_target_pct": vs.target_nrmse_pct,
            "wind_target_pct": vc.wind.target_nrmse_pct,
            "config_loss_pct": s.solar.loss_pct,
            "local_timezone": vs.local_timezone,
        },
    }
    return metrics, series, caps


def gate(m: dict) -> bool:
    """Plant 1 + wind only; non-gating plants never affect the result (D-L2)."""
    solar_ok = all(p["pass"] and p["pass_at_config_loss"] for p in m["solar"].values() if p["gating"])
    return solar_ok and m["wind"]["pass"]


def run(args, out_dir: Path | None = None, notes_path: Path | None = None) -> int:
    s, vc = load_settings(), load_validation_cfg()
    metrics, series, caps = validate_all(s, vc, require_kaggle_files(s))
    write_outputs(
        metrics, series, out_dir or REPORTS_DIR / "validation", notes_path or DOCS_DIR / "data_notes.md", caps
    )
    print(render_validation(metrics))
    return 0 if gate(metrics) else 1
