"""Offline, deterministic coverage tables from cached sidecars + the probe dict (DATA-05). No network."""

import json
import re
from pathlib import Path

from swf.coverage.probe import is_eligible
from swf.core.settings import Settings

YEAR_STEM = re.compile(r"^\d{4}(_day\d)?$")
KT_NOTE = "ALLSKY_KT is structurally missing at night (-999 -> NaN), not a data gap."


def _table(head: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join("" if c is None else str(c) for c in r) + " |" for r in rows]
    return out + [""]


def _pct(v) -> str:
    return "n/a" if v is None else f"{v:.1f}"


def _load(raw_root: Path, s: Settings) -> dict:
    """source key -> list of (year, lead|None, sidecar). Probe/smoke/live/non-configured dirs are skipped."""
    om = s.data.openmeteo
    wanted = {
        ("nasa",): "nasa",
        ("openmeteo", "archive", om.era5_model): "era5",
        ("openmeteo", "historical_forecast", om.nwp_model): "hf",
        ("openmeteo", "previous_runs", om.nwp_model): "pr",
    }
    out: dict[str, list] = {k: [] for k in wanted.values()}
    for p in sorted(raw_root.rglob("*.meta.json")):
        rel = p.relative_to(raw_root).parts
        key = wanted.get(rel[:-1])
        stem = p.name[: -len(".meta.json")]
        if key is None or not YEAR_STEM.match(stem):
            continue
        lead = int(stem[-1]) if "_day" in stem else None
        out[key].append((int(stem[:4]), lead, json.loads(p.read_text(encoding="utf-8"))))
    return out


def _by_year(recs: list) -> dict[int, dict]:
    return {y: m["pct_missing"] for y, _, m in sorted(recs, key=lambda r: r[0])}


def _pr_cells(recs: list) -> dict[tuple[int, int], dict]:
    cells: dict[tuple[int, int], dict] = {}
    for y, _, m in recs:
        for col, v in m["pct_missing"].items():
            var, _, lead = col.partition("_previous_day")
            cells.setdefault((y, int(lead)), {})[var] = v
    return dict(sorted(cells.items()))


def _years(t: tuple[int, int]) -> list[int]:
    return list(range(t[0], t[1] + 1))


def build_report(raw_root: Path, probe: dict, s: Settings) -> str:
    om, nasa = s.data.openmeteo, s.data.nasa
    src = _load(raw_root, s)
    hourly = list(om.hourly)
    leads = list(om.previous_day_leads)
    nwp = om.nwp_model
    pm = probe["models"].get(nwp, {})
    stamps = [probe["retrieved_utc"]] + [m["retrieved_utc"] for r in src.values() for *_, m in r]
    L = [
        f"Generated by `python -m swf coverage` from cached sidecars + probe of {probe['probe_date']}; "
        f"stamp {max(stamps)}. Do not edit inside this block.",
        "",
    ]

    ok, why = is_eligible(nwp, pm) if pm else (False, ["not in probe"])
    if not ok:
        L += [f"WARNING: configured nwp_model {nwp} is NOT eligible: {'; '.join(why[:3])}", ""]

    # 1. grid / elevation
    L += ["### Grid and elevation", ""]
    rows = [["config", "-", s.site.latitude, s.site.longitude, s.site.elevation_m]]
    if src["nasa"]:
        c = src["nasa"][0][2]["coordinates"]
        rows.append(["NASA POWER", "-", c[1], c[0], c[2]])
    for key, label in (("era5", "ERA5"), ("hf", "Historical Forecast"), ("pr", "Previous Runs")):
        if src[key]:
            m = src[key][0][2]
            rows.append([label, om.era5_model if key == "era5" else nwp, m["latitude"], m["longitude"], m["elevation"]])
    for name in om.probe_models:
        g = probe["models"].get(name, {}).get("grid")
        if g:
            rows.append(["probe", name, g["latitude"], g["longitude"], g["elevation"]])
    L += _table(["source", "model", "lat", "lon", "elevation m"], rows)

    # 2. inventory
    L += ["### Inventory", ""]
    exp = {"nasa": _years((nasa.start_year, nasa.end_year)), "era5": _years(om.era5_years),
           "hf": _years(om.historical_forecast_years), "pr": _years(om.previous_runs_years)}
    rows = []
    for k, label in (("nasa", "NASA POWER"), ("era5", "ERA5"), ("hf", "Historical Forecast"), ("pr", "Previous Runs")):
        have = {y for y, _, _ in src[k]}
        miss = [y for y in exp[k] if y not in have]
        rows.append([label, f"{exp[k][0]}-{exp[k][-1]}", len(have), ", ".join(map(str, miss)) or "none"])
    L += _table(["source", "expected years", "years present", "missing years"], rows)

    # 3. NASA
    L += ["### NASA POWER: % missing per year", ""]
    cols = list(nasa.parameters)
    L += _table(["year"] + cols, [[y] + [_pct(p.get(c)) for c in cols] for y, p in _by_year(src["nasa"]).items()])
    L += [f"Note: {KT_NOTE}", ""]
    nt = probe.get("nasa_tail", {})
    L += ["NASA data-through (probe): " + ", ".join(f"{k} {v}" for k, v in sorted(nt.items())), ""]

    # 4. ERA5
    e = probe["era5"]
    L += ["### ERA5 (models=era5)", ""]
    L += _table(["variable", "first valid (1940 window)", "first valid (earliest cached year)", "data-through"],
                [[v, e["first_valid_1940"].get(v), e["first_valid_cached"].get(v), e["last_valid"].get(v)] for v in hourly])
    L += _table(["year"] + hourly, [[y] + [_pct(p.get(v)) for v in hourly] for y, p in _by_year(src["era5"]).items()])

    # 5. HF
    L += [f"### Historical Forecast ({nwp}): % missing per year", ""]
    L += _table(["year"] + hourly, [[y] + [_pct(p.get(v)) for v in hourly] for y, p in _by_year(src["hf"]).items()])

    # 6. PR
    L += [f"### Previous Runs ({nwp}): % missing per year and lead day", ""]
    L += _table(["year", "lead day"] + hourly,
                [[y, n] + [_pct(p.get(v)) for v in hourly] for (y, n), p in _pr_cells(src["pr"]).items()])

    # 7. upper-level wind
    L += ["### Upper-level wind (80 m / 120 m)", ""]
    pr_cells = _pr_cells(src["pr"])
    rows = []
    for v in ("wind_speed_80m", "wind_speed_120m"):
        entries = [
            ("ERA5", e["first_valid_cached"].get(v), _by_year(src["era5"]), v),
            ("Historical Forecast", pm.get("hf", {}).get(v), _by_year(src["hf"]), v),
        ] + [
            (f"Previous Runs day{n}", pm.get("pr", {}).get(f"{v}_previous_day{n}"),
             {y: p for (y, ln), p in pr_cells.items() if ln == n}, v)
            for n in leads
        ]
        for label, first, per_year, var in entries:
            by_year = "; ".join(f"{y}: {_pct(p.get(var))}" for y, p in per_year.items())
            rows.append([v, label, first, by_year])
    L += _table(["variable", "source", "first valid", "% missing by year"], rows)

    # 8. per-model first valid
    for name in om.probe_models:
        m = probe["models"].get(name)
        if not m:
            continue
        L += [f"### First valid per variable: {name}", ""]
        L += _table(["variable", "HF"] + [f"PR day{n}" for n in leads],
                    [[v, m["hf"].get(v)] + [m["pr"].get(f"{v}_previous_day{n}") for n in leads] for v in hourly])

    # 9. eligibility
    L += ["### NWP model eligibility", ""]
    rows = []
    for name in om.probe_models:
        if name not in probe["models"]:
            continue
        good, reasons = is_eligible(name, probe["models"][name])
        rows.append([name, "eligible" if good else "ineligible", "chosen" if name == nwp else "",
                     "; ".join(reasons[:2])])
    L += _table(["model", "rule", "configured", "first failing reasons"], rows)
    return "\n".join(L)
